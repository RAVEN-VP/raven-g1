
"""RAVEN: quantify static framing alignment and dynamic tracking residuals.

Reads the independent tripod-camera framing CSV generated by
raven_g1_framing_verification.py. This is OFFLINE evaluation only; it neither
moves the G1 nor edits the validated controller or the original observations.

Important: bias-subtracted errors are diagnostic residuals, NOT genuine
post-correction cinematography framing accuracy. A later physical calibration
and independent verification run are required.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import statistics
from pathlib import Path


def finite_float(value):
    try:
        number = float(value)
        return number if math.isfinite(number) else None
    except (ValueError, TypeError):
        return None


def average(values):
    return statistics.mean(values) if values else None


def percentile_absolute(values, q):
    magnitudes = sorted(abs(v) for v in values)
    if not magnitudes:
        return None
    rank = max(
        0,
        min(
            len(magnitudes) - 1,
            math.ceil(q * len(magnitudes)) - 1,
        ),
    )
    return magnitudes[rank]


def rounded(value, digits=5):
    return None if value is None else round(value, digits)


def analyse(input_csv: Path, output_dir: Path, stationary_seconds: float):
    if not input_csv.is_file():
        raise FileNotFoundError(
            f"Framing CSV not found: {input_csv}"
        )

    output_dir.mkdir(parents=True, exist_ok=True)

    with input_csv.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        required = {
            "tracking_time_s",
            "horizontal_error_deg",
            "vertical_error_deg",
            "actual_pan_deg",
            "g1_target_bearing_deg",
            "tripod_detected",
        }

        missing = required.difference(reader.fieldnames or [])
        if missing:
            raise RuntimeError(
                f"CSV is missing required columns: {sorted(missing)}"
            )

        original_rows = list(reader)

    records = []

    for row in original_rows:
        detected = (
            str(row["tripod_detected"]).strip().lower()
            in {"true", "1", "yes"}
        )

        if not detected:
            continue

        measurement = {
            field: finite_float(row.get(field))
            for field in (
                "tracking_time_s",
                "horizontal_error_deg",
                "vertical_error_deg",
                "actual_pan_deg",
                "g1_target_bearing_deg",
            )
        }

        if any(value is None for value in measurement.values()):
            continue

        records.append(measurement)

    if len(records) < 20:
        raise RuntimeError(
            "At least 20 finite detected frames are needed for analysis"
        )

    records.sort(key=lambda row: row["tracking_time_s"])

    first_time = records[0]["tracking_time_s"]

    stationary = [
        row
        for row in records
        if first_time
        <= row["tracking_time_s"]
        <= first_time + stationary_seconds
    ]

    if len(stationary) < 5:
        raise RuntimeError(
            "Stationary calibration window has fewer than five samples"
        )

    offset_x = statistics.mean(
        row["horizontal_error_deg"] for row in stationary
    )

    offset_y = statistics.mean(
        row["vertical_error_deg"] for row in stationary
    )

    initial_pan_span = (
        max(row["actual_pan_deg"] for row in stationary)
        - min(row["actual_pan_deg"] for row in stationary)
    )

    initial_g1_span = (
        max(row["g1_target_bearing_deg"] for row in stationary)
        - min(row["g1_target_bearing_deg"] for row in stationary)
    )

    if initial_pan_span > 0.5 or initial_g1_span > 0.5:
        raise RuntimeError(
            "The selected stationary interval is not stationary: "
            f"pan range={initial_pan_span:.3f}deg, "
            f"G1 bearing range={initial_g1_span:.3f}deg. "
            "Reduce --stationary-seconds."
        )

    # The angle between the G1's measured target bearing
    # and the tripod's actual physical pan.
    x = [
        row["g1_target_bearing_deg"] - row["actual_pan_deg"]
        for row in records
    ]

    # Independently measured horizontal framing errors.
    y = [
        row["horizontal_error_deg"]
        for row in records
    ]

    mean_x = statistics.mean(x)
    mean_y = statistics.mean(y)

    xx = sum((value - mean_x) ** 2 for value in x)
    yy = sum((value - mean_y) ** 2 for value in y)

    xy = sum(
        (vx - mean_x) * (vy - mean_y)
        for vx, vy in zip(x, y)
    )

    # Descriptive least-squares relationship on this dataset.
    slope = xy / xx if xx > 1e-12 else None

    intercept = (
        mean_y - slope * mean_x
        if slope is not None else None
    )

    r_squared = (
        xy * xy / (xx * yy)
        if xx > 1e-12 and yy > 1e-12
        else None
    )

    residual_x = [
        value - offset_x
        for value in y
    ]

    residual_y = [
        row["vertical_error_deg"] - offset_y
        for row in records
    ]

    regression_residual = (
        [
            value - (intercept + slope * mismatch)
            for value, mismatch in zip(y, x)
        ]
        if slope is not None
        else []
    )

    # Preserve raw measurements and add diagnostic columns.
    output_csv = output_dir / "framing_baseline_decomposition.csv"

    fields = (
        "tracking_time_s",
        "measured_horizontal_error_deg",
        "measured_vertical_error_deg",
        "stationary_horizontal_bias_deg",
        "stationary_vertical_bias_deg",
        "bias_subtracted_horizontal_deg",
        "bias_subtracted_vertical_deg",
        "g1_bearing_minus_actual_pan_deg",
        "model_horizontal_error_deg",
        "model_residual_deg",
    )

    with output_csv.open(
        "w", newline="", encoding="utf-8"
    ) as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=fields,
        )

        writer.writeheader()

        for record, mismatch, resid in zip(
            records, x, residual_x
        ):
            model = (
                intercept + slope * mismatch
                if slope is not None else None
            )

            writer.writerow({
                "tracking_time_s": round(
                    record["tracking_time_s"], 4
                ),
                "measured_horizontal_error_deg": round(
                    record["horizontal_error_deg"], 5
                ),
                "measured_vertical_error_deg": round(
                    record["vertical_error_deg"], 5
                ),
                "stationary_horizontal_bias_deg": rounded(
                    offset_x
                ),
                "stationary_vertical_bias_deg": rounded(
                    offset_y
                ),
                "bias_subtracted_horizontal_deg": rounded(
                    resid
                ),
                "bias_subtracted_vertical_deg": rounded(
                    record["vertical_error_deg"] - offset_y
                ),
                "g1_bearing_minus_actual_pan_deg": rounded(
                    mismatch
                ),
                "model_horizontal_error_deg": rounded(
                    model
                ),
                "model_residual_deg": (
                    rounded(record["horizontal_error_deg"] - model)
                    if model is not None else None
                ),
            })

    report = {
        "milestone": (
            "RAVEN independent-tripod-camera baseline decomposition"
        ),
        "purpose": (
            "Static alignment versus dynamic tracking error"
        ),
        "input": str(input_csv),
        "samples_detected_and_finite": len(records),
        "stationary_window_s": stationary_seconds,
        "stationary_samples": len(stationary),
        "stationary_pan_range_deg": rounded(initial_pan_span),
        "stationary_g1_bearing_range_deg": rounded(initial_g1_span),
        "stationary_horizontal_alignment_deg": rounded(offset_x),
        "stationary_vertical_alignment_deg": rounded(offset_y),
        "actual_horizontal_mean_signed_error_deg": rounded(mean_y),
        "actual_horizontal_mae_deg": rounded(
            average([abs(value) for value in y])
        ),
        "actual_horizontal_p95_abs_deg": rounded(
            percentile_absolute(y, 0.95)
        ),
        "actual_vertical_mae_deg": rounded(
            average([
                abs(row["vertical_error_deg"])
                for row in records
            ])
        ),
        "bias_subtracted_horizontal_mae_deg_diagnostic_only": rounded(
            average([abs(value) for value in residual_x])
        ),
        "bias_subtracted_horizontal_p95_abs_deg_diagnostic_only": rounded(
            percentile_absolute(residual_x, 0.95)
        ),
        "bias_subtracted_vertical_mae_deg_diagnostic_only": rounded(
            average([abs(value) for value in residual_y])
        ),
        "horizontal_error_vs_g1_minus_pan": {
            "slope": rounded(slope),
            "intercept_deg": rounded(intercept),
            "r_squared_on_same_dataset": rounded(r_squared),
            "model_residual_mae_deg_same_dataset": rounded(
                average([abs(value) for value in regression_residual])
            ),
        },
        "important_limitation": (
            "The static offset is an OBSERVED framing bias, not yet an "
            "identified physical cause. Bias subtraction and model fitting "
            "are descriptive offline diagnostics; they DO NOT reduce the "
            "error visible to the real tripod camera. Validate physical "
            "alignment and predictive controls on a new independently "
            "recorded run."
        ),
        "decomposed_csv": str(output_csv),
    }

    output_json = output_dir / "framing_baseline_analysis.json"

    output_json.write_text(
        json.dumps(report, indent=2),
        encoding="utf-8",
    )

    print("\nRAVEN | Tripod-camera framing baseline")
    print("-------------------------------------")
    print(f"Valid samples:                  {len(records)}")
    print(
        f"Stationary window:              "
        f"{stationary_seconds:.2f} s ({len(stationary)} samples)"
    )
    print(f"Initial horizontal bias:        {offset_x:+.3f} deg")
    print(f"Initial vertical bias:          {offset_y:+.3f} deg")
    print(
        f"Real horizontal framing MAE:    "
        f"{report['actual_horizontal_mae_deg']:.3f} deg"
    )
    print(
        f"Bias-subtracted horizontal MAE: "
        f"{report['bias_subtracted_horizontal_mae_deg_diagnostic_only']:.3f} "
        f"deg [DIAGNOSTIC ONLY]"
    )

    if slope is not None and r_squared is not None:
        print(
            f"G1/pan mismatch regression:     "
            f"slope={slope:.3f}, R^2={r_squared:.4f}"
        )
    else:
        print("Regression unavailable")

    print(f"Report: {output_json}")
    print(f"CSV:    {output_csv}")
    print(
        "\nNo robot commands or original measurements were changed."
    )


def main():
    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=Path(
            "raven_tracking_results/tripod_framing/tripod_framing.csv"
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "raven_tracking_results/tripod_framing"
        ),
    )

    parser.add_argument(
        "--stationary-seconds",
        type=float,
        default=1.0,
    )

    args = parser.parse_args()

    if not 0.2 <= args.stationary_seconds <= 5.0:
        parser.error(
            "--stationary-seconds must be between 0.2 and 5.0"
        )

    analyse(
        args.input,
        args.output_dir,
        args.stationary_seconds,
    )


if __name__ == "__main__":
    main()
